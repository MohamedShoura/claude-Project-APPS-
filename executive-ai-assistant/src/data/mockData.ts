const months = ["Nov", "Dec", "Jan", "Feb", "Mar", "Apr"];

/** Build a plausible six-month history that trends toward the current numbers. */
function history(base: number, target: number) {
  return months.map((month, i) => {
    const ramp = 0.62 + i * 0.08;
    const noise = 0.9 + ((i * 37) % 20) / 100;
    return {
      month,
      sales: Math.round(base * ramp * noise),
      target,
      collection: Math.round(base * ramp * noise * 0.82),
    };
  });
}

